import { describe, it, expect } from "vitest";
import { chatStamp, ubDayOf } from "./time.js";

/* УБ нь UTC+8. 2026-08-06 21:34 УБ = 2026-08-06T13:34Z */
const ub = (iso) => new Date(iso);
const NOW = ub("2026-08-06T13:34:00Z"); /* Пүрэв, 2026-08-06 21:34 УБ */

describe("ubDayOf", () => {
  it("УБ-ын хуанлийн өдрөөр хөрвүүлнэ", () => {
    expect(ubDayOf(ub("2026-08-06T13:34:00Z"))).toBe("2026-08-06");
  });

  it("UTC-гээр өмнөх өдөр байсан ч УБ-д шинэ өдөр болсныг таньна", () => {
    expect(ubDayOf(ub("2026-08-06T17:00:00Z"))).toBe("2026-08-07");
  });
});

describe("chatStamp", () => {
  it("өнөөдрийн зурвасыг 'Өнөөдөр' гэж тэмдэглэнэ", () => {
    expect(chatStamp(ub("2026-08-06T05:02:00Z"), NOW)).toBe("Өнөөдөр 13:02");
  });

  it("өчигдрийн зурвасыг 'Өчигдөр' гэж тэмдэглэнэ", () => {
    expect(chatStamp(ub("2026-08-05T13:34:00Z"), NOW)).toBe("Өчигдөр 21:34");
  });

  it("7 хоногийн дотор бол гаригийн нэрээр харуулна", () => {
    /* 2026-08-03 бол Даваа */
    expect(chatStamp(ub("2026-08-03T02:00:00Z"), NOW)).toBe("Даваа 10:00");
  });

  it("7 хоногоос хол ч мөн жилийнх бол он хэлэхгүй", () => {
    expect(chatStamp(ub("2026-05-01T02:00:00Z"), NOW)).toBe("5 сарын 1, 10:00");
  });

  it("өөр жилийнх бол оноор нь хэлнэ", () => {
    expect(chatStamp(ub("2025-08-06T02:00:00Z"), NOW)).toBe("2025 оны 8 сарын 6, 10:00");
  });

  it("яг 7 хоногийн өмнөх нь гариг биш огноо болно", () => {
    expect(chatStamp(ub("2026-07-30T02:00:00Z"), NOW)).toBe("7 сарын 30, 10:00");
  });

  it("ирээдүйн огноог гариг гэж андуурахгүй", () => {
    expect(chatStamp(ub("2026-08-08T02:00:00Z"), NOW)).toBe("8 сарын 8, 10:00");
  });
});
