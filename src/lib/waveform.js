/* Дуут зурвасын долгионы баганууд.

   Жинхэнэ дууны далайцыг задлахын тулд AudioContext-оор бүх бичлэгийг тайлах
   шаардлагатай — чат нээгдэх бүрд 20 дуут зурвасыг тайлах нь утсыг зогсооно.
   Оронд нь ТУХАЙН зурвасын id-аас тогтмол долгион гаргана: жинхэнэ дуу биш ч,
   зурвас бүр өөр өөрийн дүрстэй бөгөөд дахин зурагдах бүрд ижил хэвээр байна
   (санамсаргүй бол бичлэг тоглох үед долгион нь үсэрнэ). */

export const WAVE_BARS = 28;

/* Тогтмол хуурамч санамсаргүй тоо — mulberry32. Нэг үрээс үргэлж нэг дараалал. */
const seeded = (seed) => () => {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
};

const hash = (s) => {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
};

/* 0.15-1 хооронд WAVE_BARS ширхэг өндөр. Дундуураа өндөр, хоёр үзүүр рүү
   намсдаг далайцаар үржүүлнэ — ярианы бичлэг ихэвчлэн ингэж харагддаг. */
export function waveBars(key, n = WAVE_BARS) {
  const rand = seeded(hash(String(key ?? "")));
  return Array.from({ length: n }, (_, i) => {
    const t = n === 1 ? 0.5 : i / (n - 1);
    const envelope = 0.55 + 0.45 * Math.sin(Math.PI * t); /* үзүүрт нам, дунд өндөр */
    return Math.max(0.15, Math.min(1, (0.35 + rand() * 0.65) * envelope));
  });
}
