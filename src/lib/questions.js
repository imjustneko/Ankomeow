/* FNV-1a — богино, тогтвортой, ямар ч орчинд ижил үр дүн өгнө */
function hashStr(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

export function questionIndex(dayISO) {
  return hashStr(String(dayISO)) % QUESTIONS.length;
}

export function questionForDay(dayISO) {
  return QUESTIONS[questionIndex(dayISO)];
}
