/* Зурвасын жагсаалт өөрчлөгдөхөд юу болсныг тодорхойлно.

   Гурван тохиолдол огт өөр хариу шаардана:
     first — чат анх нээгдэв       → доод талд шууд, анимацгүй
     new   — шинэ зурвас ирэв      → доод талд байвал дага, эс бөгөөс тоол
     older — хуучин зурвас ачаалав → гүйлгэлтийн байрлалыг ХАДГАЛ

   Урьд нь зөвхөн тоогоор шийддэг байсан тул хуучин зурвас ачаалахад ч
   "шинэ ирлээ" гэж ойлгож доош татах байв. Сүүлийн зурвасын id өөрчлөгдсөн
   эсэх нь хоёрыг ялгах цорын ганц найдвартай тэмдэг. */

export function listChange(prev, next) {
  if (!next.count) return { kind: "none", added: 0 };
  if (!prev.count) return { kind: "first", added: next.count };
  if (next.lastId === prev.lastId) {
    /* Сүүлчийнх хэвээр — дээрээс нэмэгдсэн эсвэл дундаас устсан.
       Хоёуланд нь харагдах байрлалыг хадгална. */
    return next.count === prev.count
      ? { kind: "none", added: 0 }
      : { kind: "older", added: next.count - prev.count };
  }
  /* Сүүлчийнх солигдсон — шинэ зурвас. Хуучин зурвас ЗЭРЭГ ачаалагдсан бол
     тооны зөрүү нь шинийн тоог хэтрүүлж болох тул доод хязгаарыг 1 гэж үзнэ. */
  return { kind: "new", added: Math.max(1, next.count - prev.count) };
}

/* Хуучин зурвас нэмэгдсэний дараа өмнөх харагдацыг сэргээх шинэ scrollTop.
   Дээр нь нэмэгдсэн өндрийг тэр чигт нь нөхнө. */
export const restoreTop = (before, after) => after.height - before.height + before.top;
