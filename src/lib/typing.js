/* "Бичиж байна" төлөвийн цаг хугацааны дүрмүүд.

   Товч дарах бүрд Firestore руу бичих нь утгагүй үнэтэй — 100 тэмдэгт бичихэд
   100 бичилт болно. Тиймээс тодорхой давтамжтайгаар л шинэчилнэ, бичихээ
   болиход нэг удаа унтраана.

   Хүлээн авагч тал нь `typing: true`-д бүрэн итгэж болохгүй: апп унтарсан,
   сүлжээ тасарсан бол унтраах бичилт хэзээ ч ирэхгүй. Тиймээс хугацаа хэтэрсэн
   төлөвийг өөрөө хүчингүй болгоно. */

export const TYPING_PING_MS = 3000;   /* бичсээр байхад дахин мэдэгдэх давтамж */
export const TYPING_STOP_MS = 4000;   /* товч дарахаа больсны дараа унтраах */
export const TYPING_STALE_MS = 9000;  /* үүнээс хуучин төлөвт итгэхгүй */

/* Дахин мэдэгдэх цаг болсон уу.
   lastAt === 0 нь "хараахан мэдэгдээгүй" гэсэн утгатай тул шууд мэдэгдэнэ.
   Үүнийг тусад нь бичсэн шалтгаан: эс бөгөөс функц нь `now` нь эрин үеийн
   том тоо байхаас хамаарна — цагийг өгдөг дуудагчид энэ нь баталгаагүй. */
export const shouldPing = (lastAt, now, every = TYPING_PING_MS) =>
  !lastAt || now - lastAt >= every;

/* Хамтрагч үнэхээр бичиж байна уу.
   `at` нь Firestore Timestamp (toMillis) эсвэл энгийн тоо байж болно. */
export function isTyping(data, now, stale = TYPING_STALE_MS) {
  if (!data?.typing) return false;
  const at = typeof data.at?.toMillis === "function" ? data.at.toMillis() : data.at;
  /* Цаг хараахан ирээгүй (serverTimestamp бичигдэж байгаа) бол итгэнэ —
     эс бөгөөс эхний хэдэн зуун мс-д үзүүлэлт анивчина. */
  if (at == null) return true;
  return now - at < stale;
}
